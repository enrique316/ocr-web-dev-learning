# a.sort(reverse=True) in list # 
"""
1. What is Reverse Sort?
👉 Reverse sort means sorting list in descending order (big to small)
👉 Instead of smallest first, we get largest first
"""
a = [1,2,3,4,]
a.sort(reverse=True)
print(a)

# Example with string list # 
names = ["ram", "Shyam", "Sita", "Geeta"]
names.sort(reverse=True)
print(names)

# Continue statement # 
"""
👉 The continue statement is used to skip the current iteration of a loop.

👉 Instead of stopping the loop, Python skips the current iteration and immediately moves to the next one.
"""
for y in range(5):
    if y == 2:
        continue
    print(y)

# another example # 
for x in range(10):
    if x ==10:
        continue
    print(x)
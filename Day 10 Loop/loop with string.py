#loop with string # 
"""
1. What is Looping with Strings?

👉 A string is a collection of characters.

👉 A for loop can read one character from a string at a time. 
A for loop reads each character one by one until it reaches the end of the word. 
"""
name = "Dimpal"
for letter in name:
    print(letter)


# Escape Characters \n # 
#example #
invoice = "NovDay20\n2025"
print(invoice)

#another example #

raw_data = "Kumar\nHaryana\nFeb2020"
print(raw_data)

# common escape characters #
"""
Escape	Meaning
\n	    New line
\t	    Tab space
\"	    Double quote inside string
\'	    Single quote inside string
\\	    Print a backslash
"""
# \t method #
raw_data = "I\tlove\tyou"
print(raw_data)

# Double quote inside string \"  \"# 

my_name = "shubhankar\"biswas\"" 
print(my_name)

# Single quote inside string \' \' # 
user_name = "abra \'ka\'dabra\'"
print(user_name)

# \\ Print a backslash # 

path = " E:\ "
print(path)


# OCR example for \n escape character # 
invoice = "IN\n200"
print(invoice)

